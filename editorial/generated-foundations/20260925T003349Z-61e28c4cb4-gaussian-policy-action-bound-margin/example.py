"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (0.5 + 0.25 * 1.5)
assert math.isclose(value, 0.875, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '관절1 샘플: μ=0.5, σ=0.25, z=1.5 → a (rad/s)', "actual": value})
value = (-0.25 + 0.125 * (-2))
assert math.isclose(value, -0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '관절2 샘플: μ=-0.25, σ=0.125, z=-2 → a (rad/s), 관절마다 σ가 다른 원소곱', "actual": value})
value = (0.875 + 0.25 * 1)
assert math.isclose(value, 1.125, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 근처 평균 μ=0.875, σ=0.25, z=1 → 상한 1을 넘는 샘플 (rad/s)', "actual": value})
value = ((1 - 0.875) / 0.25)
assert math.isclose(value, 0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 근처 평균의 상한 여유 (1 - μ)/σ, 단위 없음', "actual": value})
value = ((1 - 0) / 0.25)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '중앙 평균 μ=0, σ=0.25의 상한 여유, 단위 없음', "actual": value})
value = ((1 - 0.875) / 0.0625)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 경계 근처 평균에서 σ를 0.0625로 줄였을 때의 여유', "actual": value})
value = ((1.125 - 0.5) / 0.25)
assert math.isclose(value, 2.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 같은 샘플 1.125를 평균 0.5, σ 0.25에서 얻으려면 필요한 z', "actual": value})
value = ((-0.25 - (-1)) / 0.125)
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '관절2 하한 여유: μ=-0.25에서 하한 -1까지, σ=0.125', "actual": value})
value = (((0.875 - 0.5) / 0.25) * ((0.875 - 0.5) / 0.25) + ((-0.5 + 0.25) / 0.125) * ((-0.5 + 0.25) / 0.125))
assert math.isclose(value, 6.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '로그우도 이차항 합: 관절1 ((0.875-0.5)/0.25)^2 + 관절2 ((-0.5+0.25)/0.125)^2', "actual": value})
print(json.dumps(results, ensure_ascii=False))
