"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (256*1024)
assert math.isclose(value, 262144, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '기본 조각 재조립 버퍼 크기(바이트, 256KB)', "actual": value})
value = (262144/1000000)
assert math.isclose(value, 0.262144, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1MB/s 토픽이 전부 미완성 조각이면 기본 버퍼가 차는 시간(초)', "actual": value})
value = (1000000*30)
assert math.isclose(value, 30000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1MB/s 토픽을 ipfrag_time 기본 30초 동안 담는 데 필요한 바이트', "actual": value})
value = (1000000*3)
assert math.isclose(value, 3000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'ipfrag_time을 3초로 줄였을 때 필요한 바이트', "actual": value})
value = (30/3)
assert math.isclose(value, 10, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '30초에서 3초로 줄이면 필요한 버퍼가 몇 분의 1이 되는가', "actual": value})
value = (134217728/262144)
assert math.isclose(value, 512, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '권장 상한 128MB가 기본 버퍼의 몇 배인가', "actual": value})
value = (30000000/134217728)
assert math.isclose(value, 0.22351741790771484, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1MB/s·30초 필요량이 128MB 상한에서 차지하는 비율', "actual": value})
value = (5000*30)
assert math.isclose(value, 150000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 5KB/s 작은 토픽의 30초 치 바이트(기본 버퍼 262144 이하)', "actual": value})
value = (262144-5000*30)
assert math.isclose(value, 112144, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 토픽이 기본 버퍼에 남기는 여유(바이트)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
