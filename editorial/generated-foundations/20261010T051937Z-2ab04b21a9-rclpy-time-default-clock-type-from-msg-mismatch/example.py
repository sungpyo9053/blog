"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1.5 * 1000000000)
assert math.isclose(value, 1500000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Time(seconds=1.5)가 내부에 저장하는 나노초', "actual": value})
value = (2 * 1000000000 + 500000000)
assert math.isclose(value, 2500000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Time(seconds=2, nanoseconds=500000000)의 합산 나노초(두 인자가 더해진다)', "actual": value})
value = ((1500000000 - 500000000) / 1000000000)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1500000000 ns를 to_msg()로 분해할 때의 sec(10^9로 나눈 몫)', "actual": value})
value = (1500000000 - 1 * 1000000000)
assert math.isclose(value, 500000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 분해의 nanosec(나머지)', "actual": value})
value = (1 * 1000000000 + 500000000)
assert math.isclose(value, 1500000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'sec=1, nanosec=500000000 메시지를 Time.from_msg()로 되돌린 나노초', "actual": value})
value = (1500000000 - 1500000000)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '원래 Time(seconds=1.5)과 왕복 결과의 나노초 차이: 0이지만 SYSTEM_TIME 대 ROS_TIME이라 ==는 TypeError', "actual": value})
value = (0 * 1000000000 + 0)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '인자 없는 Time()의 나노초(현재 시각이 아니라 기본값 0)', "actual": value})
value = (1 + 1 + 1 + 1 + 1 + 1)
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'clock_type 불일치 시 TypeError를 직접 던지는 메서드 수(__sub__, __eq__, __lt__, __le__, __gt__, __ge__)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
