"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1 / 16)
assert math.isclose(value, 0.0625, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '16 Hz 카메라의 시뮬레이션 주기 (s)', "actual": value})
value = (0.0625 / 0.25)
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '처리 시간 0.25 s일 때 결과를 놓치지 않는 RTF 상한', "actual": value})
value = (0.25 * 1 / 0.0625)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'RTF 1에서 처리 한 번 동안 도착하는 프레임 수', "actual": value})
value = (0.0625 / (0.25 * 1))
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'RTF 1, keep last 1에서 처리되는 프레임 비율', "actual": value})
value = (0.25 * 0.5 / 0.0625)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'RTF 0.5에서 처리 한 번 동안 도착하는 프레임 수', "actual": value})
value = (0.25 * 0.25 / 0.0625)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'RTF 0.25(상한)에서 처리 한 번 동안 도착하는 프레임 수', "actual": value})
value = (0.0625 / 0.375)
assert math.isclose(value, 0.16666666666666666, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '최악 처리 시간 0.375 s 기준 RTF 상한', "actual": value})
value = (0.375 * 0.25 / 0.0625)
assert math.isclose(value, 1.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '평균 기준 상한 0.25를 쓸 때 최악 프레임에서 쌓이는 프레임 수', "actual": value})
value = (0.25 * (1 - 0.2))
assert math.isclose(value, 0.2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '상한 0.25에 20% 여유를 둔 목표 RTF', "actual": value})
value = (60 / 0.25)
assert math.isclose(value, 240, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시뮬레이션 60 s를 RTF 0.25로 돌릴 때 벽시계 시간 (s)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
