"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1920 * 1080)
assert math.isclose(value, 2073600, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1920x1080 한 프레임의 픽셀 수', "actual": value})
value = (1920 * 1080 * 3)
assert math.isclose(value, 6220800, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1920x1080 rgb8(픽셀당 3바이트 가정) 한 프레임 바이트', "actual": value})
value = (1920 * 1080 * 3 * 30 / 1000000)
assert math.isclose(value, 186.624, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1920x1080 rgb8 30 fps의 초당 MB', "actual": value})
value = (640 * 480 * 3 * 30 / 1000000)
assert math.isclose(value, 27.648, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '640x480 rgb8 30 fps의 초당 MB', "actual": value})
value = ((1920 * 1080) / (640 * 480))
assert math.isclose(value, 6.75, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1920x1080을 640x480으로 낮출 때 데이터 감소 배수', "actual": value})
value = (1920 / 2)
assert math.isclose(value, 960, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '보정 width 1920, binning_x=2일 때 받은 이미지가 가져야 할 가로 픽셀 수(CameraInfo 점검 기준)', "actual": value})
value = ((1920 / 2) * (1080 / 2) * 3)
assert math.isclose(value, 1555200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1920x1080에 binning_x=binning_y=2 적용 시 프레임 바이트', "actual": value})
value = (10 * 1920 * 1080 * 3 / 1000000)
assert math.isclose(value, 62.208, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '기본 QoS keep last 10이 붙잡을 수 있는 1920x1080 rgb8 상한(MB)', "actual": value})
value = (1 * 1920 * 1080 * 3 / 1000000)
assert math.isclose(value, 6.2208, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 비교: keep last depth 1일 때 상한(MB)', "actual": value})
value = (3840 * 2160 * 3 * 30 / 1000000)
assert math.isclose(value, 746.496, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 성격의 상한: 3840x2160 rgb8 30 fps의 초당 MB', "actual": value})
print(json.dumps(results, ensure_ascii=False))
