"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (30 * 2.0)
assert math.isclose(value, 60, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '30 Hz 카메라, 녹화기를 timer로 2초 늦춰 시작: 구독 전 발행 수', "actual": value})
value = (30 * 0.5)
assert math.isclose(value, 15, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 카메라, 지연을 0.5초로 줄였을 때', "actual": value})
value = (200 * 2.0)
assert math.isclose(value, 400, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '200 Hz IMU, 2초 지연', "actual": value})
value = ((30 + 200) * 2.0)
assert math.isclose(value, 460, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라와 IMU를 함께 녹화할 때 2초 지연 동안 발행된 합계', "actual": value})
value = (30 * 3)
assert math.isclose(value, 90, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '--use-sim-time, 녹화기 시작 후 첫 /clock이 3초 뒤 도착: 쓰이지 않는 카메라 메시지', "actual": value})
value = (3 / 60)
assert math.isclose(value, 0.05, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 조건에서 60초 녹화 가운데 비는 시간 비율', "actual": value})
value = (30 * 0)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계: 첫 /clock이 녹화기 시작과 동시에 도착', "actual": value})
value = (1 - 1)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '녹화 전에 한 번 발행된 /tf_static, 녹화기 구독이 transient_local일 때 빠지는 개수(발행 1 − 늦게 붙어도 받는 1)', "actual": value})
value = (1 - 0)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 같은 /tf_static인데 QoS override가 transient_local을 빠뜨렸을 때 빠지는 개수(발행 1 − 받는 0)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
