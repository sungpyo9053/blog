"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (200 * 60)
assert math.isclose(value, 12000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '/imu 기대 메시지 수: 200 Hz × 60 s', "actual": value})
value = (10 * 60)
assert math.isclose(value, 600, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '/scan 기대 메시지 수: 10 Hz × 60 s', "actual": value})
value = (15 * 60)
assert math.isclose(value, 900, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '/camera/image_raw 기대 메시지 수: 15 Hz × 60 s', "actual": value})
value = (12000 + 600 + 900)
assert math.isclose(value, 13500, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '변환 전 bag 총 메시지 수', "actual": value})
value = (600 - 600)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '통과 기준: 토픽별 개수가 모두 같을 때 /scan 차이(다른 토픽도 같은 방식으로 0이어야 함)', "actual": value})
value = (12000 + 600 + 0)
assert math.isclose(value, 12600, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 A: 카메라 토픽이 통째로 빠졌을 때 변환 후 총합', "actual": value})
value = (900 / 13500)
assert math.isclose(value, 0.06666666666666667, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 A의 총합 감소 비율: 토픽 하나가 사라져도 전체의 약 6.7%', "actual": value})
value = ((900 - 0) / 900)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 A의 카메라 토픽 손실 비율: 토픽 단위로는 100%', "actual": value})
value = ((12000 - 900) + 600 + 900)
assert math.isclose(value, 12600, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 B: /imu에서 900개가 빠졌을 때 변환 후 총합(반례 A와 같음)', "actual": value})
value = (900 / 12000)
assert math.isclose(value, 0.075, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 B의 /imu 손실 비율: 총합은 같아도 토픽 단위로는 7.5%', "actual": value})
print(json.dumps(results, ensure_ascii=False))
