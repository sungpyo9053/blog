"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (6*5+5)
assert math.isclose(value, 35, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '6×6 행 우선 배열에서 yaw 분산(행 5, 열 5)의 인덱스', "actual": value})
value = ((6*1+1)-(6*0+0))
assert math.isclose(value, 7, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x 분산(0,0)에서 y 분산(1,1)까지의 대각 간격: 대각 원소는 7칸마다 놓인다', "actual": value})
value = (6*0+5)
assert math.isclose(value, 5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x와 yaw의 공분산(행 0, 열 5)의 인덱스', "actual": value})
value = (6*5+0)
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '대칭 짝인 yaw와 x의 공분산(행 5, 열 0)의 인덱스: 5번 칸과 같은 값이 들어가야 한다', "actual": value})
value = (3*2+2)
assert math.isclose(value, 8, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '3×3 선가속도 공분산에서 z 분산(행 2, 열 2)의 인덱스', "actual": value})
value = (6*6+6)
assert math.isclose(value, 42, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 1부터 센 행·열 번호(6,6)를 0 기반 공식에 넣은 결과, 마지막 인덱스 35를 넘는다', "actual": value})
value = (0.1*0.1)
assert math.isclose(value, 0.01, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'yaw 표준편차 0.1 rad을 분산(rad²)으로 바꾼 값', "actual": value})
value = (0.1/(0.1*0.1))
assert math.isclose(value, 10, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 표준편차 0.1을 분산 칸에 그대로 넣었을 때 올바른 분산 대비 배율', "actual": value})
value = ((5*3.141592653589793/180)*(5*3.141592653589793/180))
assert math.isclose(value, 0.007615435494667715, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '표준편차 5도를 radian으로 바꾼 뒤 제곱한 분산(rad²)', "actual": value})
value = (25/((5*3.141592653589793/180)*(5*3.141592653589793/180)))
assert math.isclose(value, 3282.806350011744, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 도 단위 분산 25를 rad² 칸에 넣었을 때 올바른 값 대비 배율', "actual": value})
print(json.dumps(results, ensure_ascii=False))
