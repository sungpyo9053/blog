"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1000 / 20)
assert math.isclose(value, 50, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '20 Hz 카메라의 발행 주기, 곧 정상 동작 중 노드 전체의 최대 발행 공백(ms)', "actual": value})
value = (2000 - 2000)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'lease 호환성: 구독자 요청 2000 − 발행자 제공 2000 (0 이상이면 호환)', "actual": value})
value = (1000 - 2000)
assert math.isclose(value, -1000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'lease 비호환 반례: 구독자 요청 1000 − 발행자 제공 2000 (음수면 연결 없음)', "actual": value})
value = (800 - 50)
assert math.isclose(value, 750, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '정상 동작 반례: lease 800 − 카메라 주기 50 (양수면 카메라가 도는 동안 잃음으로 판정되지 않음)', "actual": value})
value = (2000 - 1000)
assert math.isclose(value, 1000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라만 멈춤: lease 2000 − 진단 주기 1000 (양수면 노드가 계속 살아 있음으로 판정되어 고장이 가려짐)', "actual": value})
value = (10000 + 100)
assert math.isclose(value, 10100, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 마지막 프레임 10000 ms 뒤 deadline missed 판정 시각(ms)', "actual": value})
value = (10000 + 2000)
assert math.isclose(value, 12000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '노드 전체가 10000 ms에 멈췄을 때 liveliness 잃음 판정 시각(ms)', "actual": value})
value = (2000 / 100)
assert math.isclose(value, 20, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '노드 전체 소실을 감지할 때 liveliness가 deadline보다 늦는 배수', "actual": value})
value = (800 - 1000)
assert math.isclose(value, -200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '고장 상태 경계: 카메라가 멈춘 뒤 lease 800 − 진단 주기 1000 (음수면 남은 진단 발행 사이에 잃음 조건에 해당)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
