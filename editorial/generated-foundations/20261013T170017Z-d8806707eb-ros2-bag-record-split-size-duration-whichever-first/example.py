"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1000000 * 30)
assert math.isclose(value, 30000000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 녹화 데이터율(B/s) = 메시지 크기 × 발행 주기', "actual": value})
value = (900000000 / 30000000)
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 녹화: -b 900000000이 채워지는 데 걸리는 시간(초)', "actual": value})
value = (60 - 900000000 / 30000000)
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 녹화: -d 60과의 차(초). 양수면 크기 기준이 먼저 자른다', "actual": value})
value = (900000000 / 200000)
assert math.isclose(value, 4500, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '저속 녹화(200000 B/s): -b가 채워지는 데 걸리는 시간(초)', "actual": value})
value = (900000000 / 200000 - 60)
assert math.isclose(value, 4440, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '저속 녹화: 크기 기준 시간에서 -d 60을 뺀 값(초). 양수면 시간 기준이 먼저 자른다', "actual": value})
value = (3600 / 30)
assert math.isclose(value, 120, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 녹화 1시간 동안 생기는 파일 수(30초 간격)', "actual": value})
value = (3600 / 60)
assert math.isclose(value, 60, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '저속 녹화 1시간 동안 생기는 파일 수(60초 간격)', "actual": value})
value = (86016 / 30000000)
assert math.isclose(value, 0.0028672, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 비교: 하한 86016바이트를 카메라 녹화가 채우는 시간(초). 이 값 자체는 허용되지 않으며 -b는 이보다 커야 한다', "actual": value})
value = (120 * 5000)
assert math.isclose(value, 600000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '카메라 녹화 1시간 동안 --repeat-transient-local로 반복 기록되는 /tf_static 추가 용량(바이트, 120개 파일 × 5000)', "actual": value})
value = (600000 / (30000000 * 3600))
assert math.isclose(value, 5.555555555555556e-06, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '그 추가 용량이 1시간 카메라 데이터 대비 차지하는 비율', "actual": value})
print(json.dumps(results, ensure_ascii=False))
