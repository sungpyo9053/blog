"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (0*1)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'QoS 표: 발행 Best effort × 구독 Reliable → reliability 0, durability 1을 곱한 연결 여부', "actual": value})
value = (1*1)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'QoS 표: 발행 Reliable × 구독 Best effort → 연결 여부', "actual": value})
value = (10*60*0)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '대조군: reliability가 맞지 않는 토픽의 60초 수신 수 (크기와 무관)', "actual": value})
value = (10*60)
assert math.isclose(value, 600, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '측정 창 60초 동안 10 Hz 토픽의 기대 수신 수 (메시지)', "actual": value})
value = (60/30)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '측정 창 길이 ÷ 기본 ipfrag_time 30초 (1보다 커야 함)', "actual": value})
value = (600*(31/32))
assert math.isclose(value, 581.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가설(best-effort, 독립 손실 1/32): 1조각 토픽의 기대 수신 수', "actual": value})
value = (600*(31/32)*(31/32)*(31/32)*(31/32))
assert math.isclose(value, 528.4429550170898, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가설(best-effort, 독립 손실 1/32): 4조각 토픽의 기대 수신 수', "actual": value})
value = ((1 - (31/32)*(31/32)*(31/32)*(31/32)) / (1/32))
assert math.isclose(value, 3.816375732421875, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가설에서 손실 확률 비: 4조각 대 1조각 (4보다 약간 작음)', "actual": value})
value = (30/3)
assert math.isclose(value, 10, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '문서 예시대로 ipfrag_time을 30초에서 3초로 줄였을 때 최대 대기 시간의 비', "actual": value})
print(json.dumps(results, ensure_ascii=False))
