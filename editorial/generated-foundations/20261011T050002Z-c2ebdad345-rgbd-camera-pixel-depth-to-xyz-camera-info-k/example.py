"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = ((420 - 320) * 2.0 / 500)
assert math.isclose(value, 0.4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'optical X (m): (u − cx)·Z/fx', "actual": value})
value = ((190 - 240) * 2.0 / 500)
assert math.isclose(value, -0.2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'optical Y (m): (v − cy)·Z/fy, 음수는 이미지 위쪽', "actual": value})
value = (500 * 0.4 / 2.0 + 320)
assert math.isclose(value, 420, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '재투영 검산 u = fx·X/Z + cx (px)', "actual": value})
value = (420 * 2.0 / 500)
assert math.isclose(value, 1.68, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: cx를 빼지 않은 X (m)', "actual": value})
value = ((420 - 320) * 2000 / 500)
assert math.isclose(value, 400, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 깊이를 mm(2000)로 넣은 X', "actual": value})
value = (1 * 2.0 / 500)
assert math.isclose(value, 0.004, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '2 m 거리에서 1픽셀 오차의 X 오차 (m)', "actual": value})
value = (500 * 0.1 / 2.0)
assert math.isclose(value, 25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '지름 0.1 m 공이 2 m에서 차지하는 픽셀 폭', "actual": value})
value = (-1 * (420 - 320) * 2.0 / 500)
assert math.isclose(value, -0.4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'REP-103 몸체 축 y(왼쪽) = −optical X (m)', "actual": value})
value = ((320 - 320) * 2.0 / 500)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계: 주점 픽셀 u = cx이면 X = 0', "actual": value})
print(json.dumps(results, ensure_ascii=False))
