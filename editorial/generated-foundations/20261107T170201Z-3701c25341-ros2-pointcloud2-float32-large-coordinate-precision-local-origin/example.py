"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (2097152 / 8388608)
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '원점에서 4,000,000 m 떨어진 좌표의 float32 간격(2^21 ÷ 2^23)', "actual": value})
value = (2097152 / 8388608 / 2)
assert math.isclose(value, 0.125, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 구간의 최대 반올림 오차(간격의 절반)', "actual": value})
value = (1 / (2097152 / 8388608))
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '4,000,000 m대에서 1 m 안에 들어가는 float32 값의 개수', "actual": value})
value = (16000001 * 0.25)
assert math.isclose(value, 4000000.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '4000000.3을 float32로 저장했을 때의 값(0.25의 배수 16000001개)', "actual": value})
value = ((400000030 - 400000025) / 100)
assert math.isclose(value, 0.05, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '4000000.3의 저장 오차(cm 정수로 계산한 뒤 m로 환산)', "actual": value})
value = ((16000000 - 16000000) * 0.25)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 5 cm 떨어진 4000000.05와 4000000.10이 둘 다 4000000.0(0.25의 배수 16000000개)으로 저장된 뒤의 차이', "actual": value})
value = (4194304 / 8388608)
assert math.isclose(value, 0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 비교: 2^22를 넘는 5,000,000 m에서의 간격(2^22 ÷ 2^23)', "actual": value})
value = ((400000030 - 399990000) / 100)
assert math.isclose(value, 100.3, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'float64 상태에서 원점 3,999,900 m를 먼저 뺀 좌표(cm 정수 계산)', "actual": value})
value = (64 / 8388608)
assert math.isclose(value, 7.62939453125e-06, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가까운 원점 기준 100 m 좌표의 float32 간격(2^6 ÷ 2^23)', "actual": value})
value = ((2097152 / 8388608) / (64 / 8388608))
assert math.isclose(value, 32768, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '원점을 옮겼을 때 간격이 줄어드는 배수', "actual": value})
print(json.dumps(results, ensure_ascii=False))
