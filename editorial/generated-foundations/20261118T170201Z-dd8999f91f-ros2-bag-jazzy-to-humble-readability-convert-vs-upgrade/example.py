"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = ((2027 - 2026) * 12 + (5 - 11))
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'humble_support_months_left_from_2026_11', "actual": value})
value = ((2029 - 2026) * 12 + (5 - 11))
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'jazzy_support_months_left_from_2026_11', "actual": value})
value = (12 - ((2027 - 2026) * 12 + (5 - 11)))
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'twelve_month_project_months_past_humble_eol', "actual": value})
value = (4 - ((2027 - 2026) * 12 + (5 - 11)))
assert math.isclose(value, -2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'four_month_project_boundary_negative_means_within_support', "actual": value})
value = (2 * 2)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'humble_read_test_cells_storage_by_state', "actual": value})
value = (2 * 2 * 5)
assert math.isclose(value, 20, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'humble_read_test_runs_with_5_repeats', "actual": value})
value = (30 + 30)
assert math.isclose(value, 60, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'peak_disk_gb_during_one_convert_30gb_bag', "actual": value})
value = (15 * 30 * 2)
assert math.isclose(value, 900, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'weekly_disk_io_gb_15_bags_read_and_write', "actual": value})
value = (15 * 4 * ((2027 - 2026) * 12 + (5 - 11)))
assert math.isclose(value, 360, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'conversions_until_humble_eol_15_per_week', "actual": value})
print(json.dumps(results, ensure_ascii=False))
