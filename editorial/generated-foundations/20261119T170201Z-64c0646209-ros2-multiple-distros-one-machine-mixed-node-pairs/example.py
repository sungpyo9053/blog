"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (6*5/2)
assert math.isclose(value, 15, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '6노드 그래프의 전체 노드 쌍 수 n(n−1)/2', "actual": value})
value = (4*3/2)
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 배포판·Fast DDS 노드 4개끼리의 쌍(보장 범위)', "actual": value})
value = (6*5/2 - 4*3/2)
assert math.isclose(value, 9, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '사례 A: 배포판이나 RMW가 달라 보장되지 않는 쌍(전체 − 같은 묶음 쌍)', "actual": value})
value = ((6*5/2 - 4*3/2) / (6*5/2))
assert math.isclose(value, 0.6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '사례 A: 보장되지 않는 쌍의 비율', "actual": value})
value = (6*5/2 - 6*5/2)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '대조군 B: 6노드가 모두 같은 배포판·같은 RMW이면 보장 밖 쌍은 0', "actual": value})
value = (6*5/2 - 5*4/2)
assert math.isclose(value, 5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 C: 같은 묶음 5개에 다른 배포판 노드 1개만 섞을 때 보장 밖 쌍 수', "actual": value})
value = ((6*5/2 - 5*4/2) / (6*5/2))
assert math.isclose(value, 0.3333333333333333, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 C: 노드 하나만 섞여도 보장 밖이 되는 쌍의 비율', "actual": value})
value = ((1*1) / (1*3))
assert math.isclose(value, 0.3333333333333333, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '토픽 하나 기준: 발행자 1개와 구독자 3개(같은 배포판 2, 다른 배포판 1) 중 배포판을 넘는 연결 비율', "actual": value})
value = ((2026-2026)*12 + (12-11))
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '두 번째 배포판이 Kilted일 때 남은 지원 개월(2026년 11월 → 2026년 12월 EOL)', "actual": value})
value = ((2031-2026)*12 + (5-11))
assert math.isclose(value, 54, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '두 번째 배포판이 Lyrical일 때 남은 지원 개월(2026년 11월 → 2031년 5월 EOL)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
