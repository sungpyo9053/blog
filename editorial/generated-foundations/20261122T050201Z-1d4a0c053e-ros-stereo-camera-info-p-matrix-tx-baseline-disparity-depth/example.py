"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (-(-84)/700)
assert math.isclose(value, 0.12, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "오른쪽 P에서 baseline 구하기: B = -Tx / fx' (m)", "actual": value})
value = (-(-84))
assert math.isclose(value, 84, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '오답: Tx를 그대로 baseline으로 읽은 값 (단위가 px·m라 m로 읽으면 700배)', "actual": value})
value = (-(-84)/750)
assert math.isclose(value, 0.112, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "오답: P의 fx' 대신 K의 fx 750을 쓴 baseline (m)", "actual": value})
value = (0/700)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계: 왼쪽(첫 번째) 카메라의 camera_info를 읽으면 Tx = 0이라 baseline도 0', "actual": value})
value = ((700*0.5+320*2.0+0)/2.0)
assert math.isclose(value, 495, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "왼쪽 영상의 가로 픽셀 x_l = (fx'·X + cx'·Z + 0) / Z", "actual": value})
value = ((700*0.5+320*2.0+(-84))/2.0)
assert math.isclose(value, 453, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "오른쪽 영상의 가로 픽셀 x_r = (fx'·X + cx'·Z + Tx) / Z", "actual": value})
value = ((700*0.5+320*2.0+0)/2.0-(700*0.5+320*2.0+(-84))/2.0)
assert math.isclose(value, 42, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "시차 d = x_l - x_r (px), fx'·B/Z = 700·0.12/2와 같아야 함", "actual": value})
value = (-(-84)/42)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": "깊이 되돌리기: Z = -Tx / d (m), fx'를 몰라도 됨", "actual": value})
value = (84/21)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가까운 점: 시차 21 px의 깊이 (m)', "actual": value})
value = (84/20)
assert math.isclose(value, 4.2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '가까운 점의 시차를 1 px 작게 읽으면 (20 px)', "actual": value})
value = (84/4)
assert math.isclose(value, 21, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '먼 점: 시차 4 px의 깊이 (m)', "actual": value})
value = (84/3)
assert math.isclose(value, 28, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '먼 점의 시차를 1 px 작게 읽으면 (3 px)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
