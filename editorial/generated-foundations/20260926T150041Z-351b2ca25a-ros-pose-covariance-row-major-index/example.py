"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (0*6+0)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '6×6 행우선에서 x 분산(0행 0열)의 인덱스', "actual": value})
value = (5*6+5)
assert math.isclose(value, 35, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '6×6 행우선에서 yaw(Z축 회전) 분산(5행 5열)의 인덱스', "actual": value})
value = (0*6+1)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x-y 공분산(0행 1열)의 인덱스', "actual": value})
value = (1*6+0)
assert math.isclose(value, 6, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '대칭 짝 y-x 공분산(1행 0열)의 인덱스: 열우선으로 착각했을 때 0행 1열이 가리키는 칸과 같음', "actual": value})
value = (2*6+2)
assert math.isclose(value, 14, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 순서를 (roll, pitch, yaw, x, y, z)로 착각하면 yaw를 2번 변수로 보고 넣는 칸, 실제로는 z 분산 칸', "actual": value})
value = (2*3+2)
assert math.isclose(value, 8, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '3×3 행우선 선형 가속도 공분산에서 z 분산(2행 2열)의 인덱스, 즉 마지막 칸', "actual": value})
value = (0.05*0.05)
assert math.isclose(value, 0.0025, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x 위치 표준편차 0.05 m를 분산(m²)으로', "actual": value})
value = ((2*3.141592653589793/180)*(2*3.141592653589793/180))
assert math.isclose(value, 0.001218469679146834, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'yaw 표준편차 2도를 rad로 바꿔 제곱한 분산(rad²)', "actual": value})
value = (4/((2*3.141592653589793/180)*(2*3.141592653589793/180)))
assert math.isclose(value, 3282.806350011744, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '도² 값 4를 rad² 칸에 그대로 넣었을 때 올바른 분산 대비 배율', "actual": value})
print(json.dumps(results, ensure_ascii=False))
