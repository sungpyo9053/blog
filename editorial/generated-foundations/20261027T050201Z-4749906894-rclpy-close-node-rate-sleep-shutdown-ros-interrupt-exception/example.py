"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1000 / 10)
assert math.isclose(value, 100, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '10 Hz 루프의 주기(ms)', "actual": value})
value = ((2350 - 50) / 100)
assert math.isclose(value, 23, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '2350 ms 셧다운 전에 정상 반환된 sleep 횟수(마지막 틱 2300 ms)', "actual": value})
value = (2350 - 2300)
assert math.isclose(value, 50, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '마지막 sleep이 셧다운 전까지 이미 기다린 시간', "actual": value})
value = (2350 - 2350)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '소스대로 이벤트가 즉시 깨울 때 셧다운 후 추가 대기', "actual": value})
value = (2400 - 2350)
assert math.isclose(value, 50, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 가정: 10 Hz에서 다음 틱 2400 ms까지 기다린다면 추가 대기', "actual": value})
value = (3000 - 2350)
assert math.isclose(value, 650, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 가정: 1 Hz 루프에서 다음 틱 3000 ms까지 기다린다면 추가 대기', "actual": value})
value = (2400 / 100)
assert math.isclose(value, 24, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계: 셧다운이 틱 2400 ms와 정확히 겹칠 때 그 틱까지의 틱 번호', "actual": value})
value = (0.5 * 650 / 1000)
assert math.isclose(value, 0.325, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례 가정에서 0.5 m/s 명령이 650 ms 더 유지될 때 이동 거리(m)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
