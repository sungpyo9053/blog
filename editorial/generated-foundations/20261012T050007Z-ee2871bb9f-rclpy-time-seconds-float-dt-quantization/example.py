"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (1/4194304)
assert math.isclose(value, 2.384185791015625e-07, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시스템 시각(약 17.9억 초) 근처 float 초의 간격 2^-22초', "actual": value})
value = (1790000000.000001 - 1790000000.0)
assert math.isclose(value, 9.5367431640625e-07, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1 µs 떨어진 두 시스템 시각을 float 초로 바꾼 뒤 뺀 dt', "actual": value})
value = ((1790000000 - 1790000000) + (1000 - 0) / 1000000000)
assert math.isclose(value, 1e-06, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 1 µs를 seconds_nanoseconds() 정수 쌍으로 먼저 뺀 dt', "actual": value})
value = (1790000000.001 - 1790000000.0)
assert math.isclose(value, 0.0009999275207519531, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1 ms 루프 주기를 float 초끼리 뺀 dt', "actual": value})
value = ((1790000000 - 1790000000) + (1000000 - 0) / 1000000000)
assert math.isclose(value, 0.001, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 1 ms를 정수 쌍으로 먼저 뺀 dt', "actual": value})
value = (1000 / 4194304)
assert math.isclose(value, 0.0002384185791015625, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1 ms 주기 대비 float 간격의 비율(시스템 시각)', "actual": value})
value = (1/70368744177664)
assert math.isclose(value, 1.4210854715202004e-14, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시뮬레이션 시각 125초 근처 float 간격 2^-46초', "actual": value})
value = (70368744177664 / 4194304)
assert math.isclose(value, 16777216, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시스템 시각과 시뮬레이션 시각의 float 간격 비(2^24)', "actual": value})
value = (1/2097152)
assert math.isclose(value, 4.76837158203125e-07, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계: 2^31초(2038년 1월)를 넘은 시스템 시각의 float 간격', "actual": value})
print(json.dumps(results, ensure_ascii=False))
