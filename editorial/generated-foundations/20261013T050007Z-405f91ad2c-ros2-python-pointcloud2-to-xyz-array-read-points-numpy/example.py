"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (640 * 480)
assert math.isclose(value, 307200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '정렬된 640x480 클라우드의 점 개수(width*height)', "actual": value})
value = (640 * 480 * 16)
assert math.isclose(value, 4915200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'data 바이트 길이(점 개수*point_step 16)', "actual": value})
value = (1000 * 16 + 8)
assert math.isclose(value, 16008, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1000번째 인덱스 점의 z가 시작하는 바이트(i*point_step+offset 8)', "actual": value})
value = (640 * 480 * (16 - 12))
assert math.isclose(value, 1228800, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x,y,z 12바이트를 point_step 16에 담을 때 생기는 전체 빈 바이트', "actual": value})
value = (307200 * 3 * 4)
assert math.isclose(value, 3686400, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'read_points_numpy로 xyz만 꺼낸 float32 배열의 바이트(점*3*4)', "actual": value})
value = (307200 - 40000)
assert math.isclose(value, 267200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'is_dense=False이고 NaN 점 40000개일 때 skip_nans=True 결과 점 개수', "actual": value})
value = (307200 - 0)
assert math.isclose(value, 307200, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: is_dense=True로 잘못 채워졌다면 skip_nans=True여도 필터가 돌지 않아 남는 점 개수', "actual": value})
value = (10 * 32 + 16)
assert math.isclose(value, 336, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '라이다 레이아웃(point_step 32)에서 10번 점의 ring(uint16, offset 16) 시작 바이트', "actual": value})
print(json.dumps(results, ensure_ascii=False))
