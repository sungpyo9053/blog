"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (2*1)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '공식 설치 테스트에 필요한 source 횟수: 터미널 2개 × 터미널당 1회', "actual": value})
value = (6-4)
assert math.isclose(value, 2, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '터미널 6개 중 4개만 source했을 때 source하지 않은 터미널 수', "actual": value})
value = (6-2-1)
assert math.isclose(value, 3, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '6개 중 미source 2개, zsh에서 setup.bash를 고른 불일치 1개를 뺀 import 예상 가능 터미널 수', "actual": value})
value = (3/6)
assert math.isclose(value, 0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '위 경우 import가 가능할 것으로 예상되는 터미널의 비율', "actual": value})
value = (6-6)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '셸 시작 파일에 source 줄을 넣어 6개 모두 자동 source됐을 때 미source 터미널 수', "actual": value})
value = (5*6)
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '5일 동안 하루 6개 터미널을 매번 손으로 source할 때의 명령 횟수', "actual": value})
value = (5*6-1)
assert math.isclose(value, 29, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 5일 동안 셸 시작 파일에 한 번만 추가했을 때 줄어드는 명령 횟수', "actual": value})
value = (6-0-6)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 사례: 6개 모두 source했지만 6개 모두 zsh에서 setup.bash를 고른 경우의 import 예상 가능 터미널 수', "actual": value})
print(json.dumps(results, ensure_ascii=False))
