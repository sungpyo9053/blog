"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (8 + 4)
assert math.isclose(value, 12, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Foo 요소 하나의 선언 필드 바이트(uint64 8 + uint32 4, 패딩 제외)', "actual": value})
value = (10000 * (8 + 4))
assert math.isclose(value, 120000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Foo[] 10000개의 선언 필드 바이트 합(직렬화 크기 아님)', "actual": value})
value = (10000 * 8 + 10000 * 4)
assert math.isclose(value, 120000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'uint64[] 10000개 + uint32[] 10000개의 선언 필드 바이트 합(직렬화 크기 아님)', "actual": value})
value = (10000 * 1)
assert math.isclose(value, 10000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Foo[] 구조에서 메시지 하나당 비기본형 요소 수', "actual": value})
value = (10000 * 1 * 30)
assert math.isclose(value, 300000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Foo[] 구조를 30 Hz로 발행할 때 초당 비기본형 요소 수', "actual": value})
value = (10000 * 0 * 30)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '기본형 배열 두 개 구조를 30 Hz로 발행할 때 초당 비기본형 요소 수(경계 사례)', "actual": value})
value = (10000 * (1 + 1))
assert math.isclose(value, 20000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Foo마다 builtin_interfaces/Time을 하나씩 넣었을 때 메시지당 비기본형 요소 수(Foo + Time)', "actual": value})
value = (10000 * (1 + 1) * 30)
assert math.isclose(value, 600000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'Time을 넣은 Foo[] 구조를 30 Hz로 발행할 때 초당 비기본형 요소 수', "actual": value})
print(json.dumps(results, ensure_ascii=False))
