"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (262144 / 1024)
assert math.isclose(value, 256, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '기본 조각 버퍼 크기(KiB)', "actual": value})
value = (262144 / 65536)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '64 KiB 불완전 데이터그램 몇 개로 기본 버퍼가 차는가(점유 가정)', "actual": value})
value = (30 * 10)
assert math.isclose(value, 300, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '30초 멈춘 구간에 10 Hz 토픽에서 발행되는 메시지 수(최대 영향 범위)', "actual": value})
value = (3 * 10)
assert math.isclose(value, 30, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'ipfrag_time 3초일 때 멈춘 구간에 발행되는 메시지 수(최대 영향 범위)', "actual": value})
value = (30 * 10 * 1048576)
assert math.isclose(value, 314572800, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '최악 가정에서 30초 대기 동안 들어오는 1 MiB·10 Hz 데이터(bytes)', "actual": value})
value = (134217728 - 30 * 10 * 1048576)
assert math.isclose(value, -180355072, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '128MB 버퍼에서 30초 분량을 뺀 값(음수면 최악 가정에서 다 담지 못함)', "actual": value})
value = (134217728 - 3 * 10 * 1048576)
assert math.isclose(value, 102760448, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '128MB 버퍼에서 3초 분량을 뺀 값', "actual": value})
value = (134217728 / 262144)
assert math.isclose(value, 512, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '버퍼를 128MB로 올렸을 때 기본값 대비 배율', "actual": value})
print(json.dumps(results, ensure_ascii=False))
