"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (0.6*(1-0.6)/20)
assert math.isclose(value, 0.012, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시드를 한 번만 줄 때: 독립 시작 20개로 구한 성공률 추정 분산 (p=0.6)', "actual": value})
value = (0.6*(1-0.6)/1)
assert math.isclose(value, 0.24, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '매번 같은 seed로 reset할 때: 시작이 하나뿐인 n=1 분산 (p=0.6)', "actual": value})
value = ((0.6*(1-0.6)/1)/(0.6*(1-0.6)/20))
assert math.isclose(value, 20, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 seed 반복이 키운 분산 배율', "actual": value})
value = (1/20)
assert math.isclose(value, 0.05, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '같은 seed 반복 시 20 에피소드 중 서로 다른 시작의 비율', "actual": value})
value = (0.5*(1-0.5)/20)
assert math.isclose(value, 0.0125, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '분산이 가장 큰 p=0.5에서 독립 시작 20개의 분산', "actual": value})
value = (0.5*(1-0.5)/1)
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '분산이 가장 큰 p=0.5에서 같은 seed 반복의 분산', "actual": value})
value = (1*(1-1)/20)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 사례 p=1: 독립 시작 20개여도 분산 0', "actual": value})
value = (1*(1-1)/1)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 사례 p=1: 같은 seed 반복이어도 분산 0, 실수가 드러나지 않음', "actual": value})
value = (1000*1)
assert math.isclose(value, 1000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1000 에피소드 학습에서 매 reset에 seed를 넘길 때 PRNG 재설정 횟수', "actual": value})
print(json.dumps(results, ensure_ascii=False))
