"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (0.5 - 1.0)
assert math.isclose(value, -0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시계 0에서 시작, 시뮬레이션 0.5초에 1초 전 시각 계산(음수 → ValueError 영역)', "actual": value})
value = (1.0 - 1.0)
assert math.isclose(value, 0, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '정확히 1.0초 경계: 예외는 없지만 결과가 초기화 안 됨을 뜻하는 시각 0', "actual": value})
value = (1.25 - 1.0)
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '1.25초: 첫 유효한 양수 시각', "actual": value})
value = (0 - 1.0)
assert math.isclose(value, -1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 시작 오프셋 100초를 줘도 첫 /clock 전에는 ROS 시간 0이라 음수', "actual": value})
value = (100 - 1.0)
assert math.isclose(value, 99, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시작 오프셋 100초, 첫 /clock 수신 뒤', "actual": value})
value = (1.0 * 10 - 1)
assert math.isclose(value, 9, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '시계 0 시작, 10 Hz 타이머에서 now가 W보다 작아 실패하는 콜백 수 (W×f−1, 0.1~0.9초 틱)', "actual": value})
value = (5 * 10 - 1)
assert math.isclose(value, 49, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '창 길이 W=5초로 늘리면 실패 콜백 수', "actual": value})
value = (1.0 / 0.25)
assert math.isclose(value, 4, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '실시간 배율 0.25에서 W=1초 구간이 벽시계로 이어지는 시간(초)', "actual": value})
value = (0.5 - 1.0)
assert math.isclose(value, -0.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '오프셋 여유: 시작 오프셋 0.5초는 W=1초보다 작아 첫 /clock 직후에도 음수', "actual": value})
print(json.dumps(results, ensure_ascii=False))
