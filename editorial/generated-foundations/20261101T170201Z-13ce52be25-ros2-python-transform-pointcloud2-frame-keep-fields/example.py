"""Purpose-built arithmetic checks; not robot or simulator execution."""
import math
import json
results = []
value = (-0.5 + 0.25)
assert math.isclose(value, -0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '변환 후 base_link x (m): −y + t_x', "actual": value})
value = (1.0 + 0)
assert math.isclose(value, 1, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '변환 후 base_link y (m): x + t_y', "actual": value})
value = (0 + 0.125)
assert math.isclose(value, 0.125, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '변환 후 base_link z (m): z + t_z', "actual": value})
value = ((1.25 + 0.25) * (1.25 + 0.25) + (0.5 - 1.0) * (0.5 - 1.0))
assert math.isclose(value, 2.5, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '반례: 회전 없이 이동만 더한 점 (1.25, 0.5)과 정답 (−0.25, 1.0)의 xy 제곱 오차 (m²)', "actual": value})
value = (1000 * 1 * 16)
assert math.isclose(value, 16000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '원본 클라우드 data 바이트: width × height × point_step 16', "actual": value})
value = (1000 * 1 * 12)
assert math.isclose(value, 12000, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": 'x·y·z 필드만으로 다시 만든 클라우드 data 바이트: point_step 12', "actual": value})
value = ((16000 - 12000) / 16000)
assert math.isclose(value, 0.25, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '다시 만들면서 줄어든 바이트 비율', "actual": value})
value = (2 * 12 + 12)
assert math.isclose(value, 36, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '새 클라우드에서 점 i=2의 intensity를 옛 offset 12로 읽을 때 바이트 위치: i × 12 + 12', "actual": value})
value = (3 * 12)
assert math.isclose(value, 36, rel_tol=1e-9, abs_tol=1e-9)
results.append({"name": '경계 비교: 새 클라우드에서 점 i=3의 x 시작 바이트 (i × 12)', "actual": value})
print(json.dumps(results, ensure_ascii=False))
