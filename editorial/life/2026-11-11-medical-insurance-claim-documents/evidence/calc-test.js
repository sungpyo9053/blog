// ko.html의 확인기 <script>를 그대로 뽑아 node에서 실행하는 검산
const fs = require('fs'), path = require('path'), assert = require('assert');
const html = fs.readFileSync(path.join(__dirname, '..', 'ko.html'), 'utf8');
const src = html.match(/<script>([\s\S]*?)<\/script>/)[1];
if (src.indexOf('&') >= 0) throw new Error('& found in script');
if (/\n\s*\n/.test(src)) throw new Error('blank line in script');
if (/'[^'\n]*<[^'\n]*'/.test(src)) throw new Error('< inside string literal');
global.window = {};
global.document = { getElementById: () => null };
eval(src);
const chk = window.silsonClaimCheck;
const has = (r, s) => r.docs.join('|').includes(s);
const T = '2026-10-28';
let r;
r = chk('out', 25000, 'yes', '2026-10-20', T);
assert.deepStrictEqual(r.docs, ['보험금 청구서', '진료비 계산서·영수증']);
assert.strictEqual(r.deadline, '2029-10-20'); assert.strictEqual(r.daysLeft, 1088);
console.log('PASS 외래 2.5만원 연계:', JSON.stringify(r));
r = chk('out', 30000, 'no', '2026-10-20', T);
assert.ok(!has(r, '처방전')); console.log('PASS 경계 3만원 정확히 -> 처방전 없음');
r = chk('out', 30001, 'no', '2026-10-20', T);
assert.ok(has(r, '처방전')); assert.ok(!has(r, '진단서')); assert.ok(r.route[0].includes('종이 서류'));
console.log('PASS 3만원 초과 -> 처방전, 미연계 -> 종이 경로');
r = chk('out', 100000, 'yes', '2026-10-20', T); assert.ok(!has(r, '진단서'));
r = chk('out', 100001, 'yes', '2026-10-20', T); assert.ok(has(r, '진단서')); assert.ok(r.route.join().includes('사진'));
console.log('PASS 10만원 경계 -> 초과 시 진단서 + 사진 첨부');
r = chk('pharm', 8000, 'yes', '2026-10-20', T); assert.ok(has(r, '약제비 계산서')); console.log('PASS 약제비');
r = chk('nonpay', 80000, 'yes', '2026-10-20', T); assert.ok(has(r, '세부산정내역서')); assert.ok(has(r, '처방전'));
console.log('PASS 비급여 8만원 -> 처방전+세부산정내역서');
r = chk('inpt', 0, 'yes', '2026-10-20', T); assert.ok(has(r, '세부산정내역서')); assert.ok(has(r, '진단서'));
console.log('PASS 입원:', r.docs.join(', '));
r = chk('out', 50000, 'yes', '2024-10-24', T); assert.ok(r.notes.join().includes('2024년 10월 25일 이전'));
r = chk('out', 50000, 'yes', '2024-10-25', T); assert.ok(!r.notes.join().includes('2024년 10월 25일 이전'));
console.log('PASS 실손24 시행일 경계 2024-10-24/25');
r = chk('out', 50000, 'no', '2023-10-27', T); assert.strictEqual(r.deadline, '2026-10-27'); assert.strictEqual(r.daysLeft, -1);
assert.ok(r.notes.join().includes('3년이 지났습니다')); console.log('PASS 3년 경과 -1일');
r = chk('out', 50000, 'no', '2023-10-28', T); assert.strictEqual(r.daysLeft, 0); assert.ok(!r.notes.join().includes('지났습니다'));
console.log('PASS 오늘이 기한 당일 0일');
r = chk('out', 5000, 'unknown', '2024-02-29', T); assert.strictEqual(r.deadline, '2027-03-01');
console.log('PASS 2/29 진료 -> 3년 뒤 3/1로 넘김(JS Date 처리)');
// UI 렌더 (DOM 스텁)
const vals = { 'sc-type': 'out', 'sc-amount': '25000', 'sc-linked': 'yes', 'sc-date': '' };
const lines = [];
const mk = () => ({ style: {}, set textContent(v) { lines.push(v); }, appendChild() {} });
const el = id => ({ get value() { return vals[id]; }, set value(v) { vals[id] = v; }, style: {}, addEventListener() {}, set innerHTML(v) { lines.length = 0; }, appendChild() {} });
const els = {}; ['sc-out', ...Object.keys(vals)].forEach(id => els[id] = el(id));
global.document = { getElementById: id => els[id], createElement: mk };
eval(src);
console.log('UI 기본값 출력:', lines.join(' | '));
assert.ok(lines.includes('진료비 계산서·영수증')); assert.ok(lines.join().includes('1,095일 남음') || lines.join().includes('일 남음'));
console.log('ALL PASS');
