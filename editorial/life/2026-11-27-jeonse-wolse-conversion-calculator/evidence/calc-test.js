// ko.html의 계산기 <script>를 그대로 뽑아 node에서 실행하는 검산
const fs = require('fs'), path = require('path'), assert = require('assert');
const html = fs.readFileSync(path.join(__dirname, '..', 'ko.html'), 'utf8');
const src = html.match(/<script>([\s\S]*?)<\/script>/)[1];
if (src.indexOf('&') >= 0) throw new Error('& found in script');
if (/\n\s*\n/.test(src)) throw new Error('blank line in script');
for (const s of src.match(/'[^']*'/g)) if (s.indexOf('<') >= 0) throw new Error('< in string ' + s);
const ld = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1];
if (/[&<]/.test(ld)) throw new Error('& or < in JSON-LD');
JSON.parse(ld);
global.window = {};
global.document = { getElementById: () => null };
eval(src);
const c = window.jeonseWolseCalc;
const eq = (a, b, m) => { assert.strictEqual(a, b, m + ' got ' + a); console.log('PASS', m, a); };
eq(c.legalRate(3), 5, '기준금리 3.00% -> 법정 5%');
eq(c.legalRate(2.75), 4.75, '기준금리 2.75% -> 4.75%');
eq(c.legalRate(9), 10, '기준금리 9% -> 상한 10%');
eq(c.toMonthly(1e8, 5), 416667, '1억 x 5% / 12');
eq(c.toMonthly(1e8, 4.5), 375000, '1억 x 4.5% / 12');
eq(c.toMonthly(1e8, 4.75), 395833, '1억 x 4.75% / 12');
eq(c.toMonthly(2e8, 4), 666667, '국토부 2020 예시 2억 x 4% (67만원)');
eq(c.toMonthly(3e8, 4), 1000000, '국토부 2020 예시 3억 x 4% (100만원)');
[[3e7, 125000], [5e7, 208333], [1e8, 416667], [2e8, 833333], [3e8, 1250000]].forEach(([a, m]) => eq(c.toMonthly(a, 5), m, '표 ' + a));
eq(c.toMonthly(1e8, 3.5), 291667, '내 비율 3.5%');
eq(c.toJeonse(1e8, 500000, 5), 220000000, '보증금1억+월50만 5% -> 2.2억');
eq(c.impliedRate(1e6, 2e8), 6, '2억 전환 월100만 -> 6%');
const r = c.compare(5e8, 3e8, 1e6, 3);
eq(r.cap, 833333, '전세5억->보증금3억 상한'); eq(r.overMonth, 166667, '초과 월'); eq(r.overYear, 2000000, '초과 연 200만');
